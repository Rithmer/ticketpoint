CREATE FUNCTION ticketpoint_touch_booking() RETURNS TRIGGER
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.version = OLD.version THEN NEW.version := OLD.version + 1; END IF;
    NEW.updated_at := LOCALTIMESTAMP;
    RETURN NEW;
END
$$;
CREATE TRIGGER booking_touch
    BEFORE UPDATE
    ON bookings
    FOR EACH ROW
EXECUTE FUNCTION ticketpoint_touch_booking();
CREATE FUNCTION ticketpoint_touch_event() RETURNS TRIGGER
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.version = OLD.version THEN NEW.version := OLD.version + 1; END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER event_touch
    BEFORE UPDATE
    ON events
    FOR EACH ROW
EXECUTE FUNCTION ticketpoint_touch_event();
