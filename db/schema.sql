CREATE TYPE booking_status AS ENUM ('NEW', 'PAID', 'CANCELLED');

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0 AND name !~ '[[:cntrl:]]'),
    CONSTRAINT customers_code_format CHECK (
        customer_code = upper(trim(customer_code))
        AND customer_code ~ '^CUS-[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}$'
    )
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CONSTRAINT events_title_valid
        CHECK (length(trim(title)) > 0 AND title !~ '[[:cntrl:]]'),
    venue VARCHAR(200) NOT NULL CONSTRAINT events_venue_valid
        CHECK (length(trim(venue)) > 0 AND venue !~ '[[:cntrl:]]'),
    starts_at TIMESTAMP NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(40) NOT NULL UNIQUE
        CONSTRAINT bookings_ticket_nonblank CHECK (length(trim(ticket_number)) > 0),
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE RESTRICT,
    price_at_booking NUMERIC(12,2) NOT NULL CHECK (price_at_booking >= 0),
    status booking_status NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_bookings_customer ON bookings(customer_id);
CREATE INDEX idx_bookings_event ON bookings(event_id);
CREATE INDEX idx_bookings_status ON bookings(status);
CREATE INDEX idx_bookings_created_at_id ON bookings(created_at DESC, id);
CREATE INDEX idx_events_starts_at_id ON events(starts_at, id);
